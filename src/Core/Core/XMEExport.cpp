namespace
{
    // what "{:f}" and "{}" write, appended without std::format: its output iterator into a string
    // pushes a character at a time (34 us a vertex, a map's world took 20 s)
    void Fixed(std::string& Out, float V)
    {
        char B[64];
        const auto R = std::to_chars(B, B + sizeof(B), V, std::chars_format::fixed, 6);
        Out.append(B, R.ptr);
    }
    void Whole(std::string& Out, uint64_t V)
    {
        char B[24];
        const auto R = std::to_chars(B, B + sizeof(B), V);
        Out.append(B, R.ptr);
    }
}

// The text built whole, then written at once
void CodXME::ExportXME(const WraithModel& Model, const std::string& FileName)
{
    std::string Out;
    Out += "// Generated by Wraith - Game extraction tools\n"
           "// Please credit DTZxPorter for using it!\n"
           "MODEL\nVERSION 6\n\n";
    std::format_to(std::back_inserter(Out), "NUMBONES {}\n", Model.BoneCount());
    uint32_t BoneIndex = 0;
    for (auto& Bone : Model.Bones)
    {
        std::format_to(std::back_inserter(Out), "BONE {} {} \"{}\"\n", BoneIndex, Bone.BoneParent, Bone.TagName.c_str());
        BoneIndex++;
    }
    Out += '\n';
    BoneIndex = 0;
    for (auto& Bone : Model.Bones)
    {
        Matrix RotationMatrix = Matrix::CreateFromQuaternion(Bone.GlobalRotation);
        std::format_to(std::back_inserter(Out),
            "BONE {}\n"
            "OFFSET {:f}, {:f}, {:f}\n"
            "SCALE {:f}, {:f}, {:f}\n"
            "X {:f}, {:f}, {:f}\n"
            "Y {:f}, {:f}, {:f}\n"
            "Z {:f}, {:f}, {:f}\n\n",
            BoneIndex,
            Bone.GlobalPosition.X, Bone.GlobalPosition.Y, Bone.GlobalPosition.Z,
            Bone.BoneScale.X, Bone.BoneScale.Y, Bone.BoneScale.Z,
            VectorMath::Clamp(RotationMatrix.Mat(0, 0), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(0, 1), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(0, 2), -1.0f, 1.0f),
            VectorMath::Clamp(RotationMatrix.Mat(1, 0), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(1, 1), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(1, 2), -1.0f, 1.0f),
            VectorMath::Clamp(RotationMatrix.Mat(2, 0), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(2, 1), -1.0f, 1.0f), VectorMath::Clamp(RotationMatrix.Mat(2, 2), -1.0f, 1.0f));
        BoneIndex++;
    }
    auto VertexCount = Model.VertexCount();
    auto FaceCount = Model.FaceCount();
    const char* Vert = VertexCount > UINT16_MAX ? "VERT32" : "VERT";
    std::format_to(std::back_inserter(Out), "{} {}\n", VertexCount > UINT16_MAX ? "NUMVERTS32" : "NUMVERTS", VertexCount);
    std::unordered_set<int32_t> MaterialIndicies;
    uint32_t VertexIndex = 0;
    for (auto& Submesh : Model.Submeshes)
    {
        MaterialIndicies.insert(Submesh.MaterialIndicies[0]);
        for (auto& Vertex : Submesh.Verticies)
        {
            Out += Vert;
            Out += ' ';
            Whole(Out, VertexIndex);
            Out += "\nOFFSET ";
            Fixed(Out, Vertex.Position.X);
            Out += ", ";
            Fixed(Out, Vertex.Position.Y);
            Out += ", ";
            Fixed(Out, Vertex.Position.Z);
            Out += '\n';
            if (Vertex.WeightCount() == 1)
            {
                Out += "BONES 1\nBONE ";
                Whole(Out, Vertex.Weights[0].BoneIndex);
                Out += " 1.000000\n\n";
            }
            else
            {
                std::format_to(std::back_inserter(Out), "BONES {}\n", (uint32_t)Vertex.WeightCount());
                for (auto& Weight : Vertex.Weights) std::format_to(std::back_inserter(Out), "BONE {} {:f}\n", Weight.BoneIndex, Weight.Weight);
                Out += '\n';
            }
            VertexIndex++;
        }
    }
    std::format_to(std::back_inserter(Out), "NUMFACES {}\n", FaceCount);
    uint32_t SubmeshIndex = 0;
    VertexIndex = 0;
    for (auto& Submesh : Model.Submeshes)
    {
        auto FindResult = MaterialIndicies.find(Submesh.MaterialIndicies[0]);
        uint32_t IndexOfMaterial = (FindResult != MaterialIndicies.end()) ? (uint32_t)std::distance(MaterialIndicies.begin(), FindResult) : 0;
        const auto Corner = [&](uint32_t Index) {
            const auto& V = Submesh.Verticies[Index];
            const auto Floats = [&](const char* Label, std::initializer_list<float> Values) {
                Out += Label;
                for (const float F : Values)
                {
                    Out += ' ';
                    Fixed(Out, F);
                }
                Out += '\n';
            };
            Out += Vert;
            Out += ' ';
            Whole(Out, (uint64_t)Index + VertexIndex);
            Out += '\n';
            Floats("NORMAL", { V.Normal.X, V.Normal.Y, V.Normal.Z });
            Floats("COLOR", { V.Color[0] / 255.0f, V.Color[1] / 255.0f, V.Color[2] / 255.0f, V.Color[3] / 255.0f });
            Floats("UV 1", { V.UVLayers[0].U, V.UVLayers[0].V });
        };
        for (auto& Face : Submesh.Faces)
        {
            Out += "TRI ";
            Whole(Out, SubmeshIndex);
            Out += ' ';
            Whole(Out, IndexOfMaterial);
            Out += " 0 0\n";
            Corner(Face.Index3);
            Corner(Face.Index1);
            Corner(Face.Index2);
        }
        VertexIndex += Submesh.VertexCount();
        SubmeshIndex++;
    }
    Out += '\n';
    std::format_to(std::back_inserter(Out), "NUMOBJECTS {}\n", Model.SubmeshCount());
    SubmeshIndex = 0;
    for (auto& Submesh : Model.Submeshes)
    {
        std::format_to(std::back_inserter(Out), "OBJECT {} \"WraithMesh_{}\"\n", SubmeshIndex, SubmeshIndex);
        SubmeshIndex++;
    }
    Out += '\n';
    std::format_to(std::back_inserter(Out), "NUMMATERIALS {}\n", (uint32_t)MaterialIndicies.size());
    uint32_t MaterialIndex = 0;
    for (auto& MaterialOffset : MaterialIndicies)
    {
        const WraithMaterial& Material = (MaterialOffset > -1) ? Model.Materials[MaterialOffset] : WraithMaterial::DefaultMaterial;
        std::format_to(std::back_inserter(Out), "MATERIAL {} \"{}\" \"Phong\" \"", MaterialIndex, Material.MaterialName.c_str());
        // Ensure we don't exceed 128 characters, APE (and probably Linker) limits it...
        if (!Strings::IsNullOrWhiteSpace(Material.DiffuseMapName) && Material.DiffuseMapName.size() < 112)
            std::format_to(std::back_inserter(Out), "color:{}", Material.DiffuseMapName.c_str());
        Out += "\"\nCOLOR 0.000000 0.000000 0.000000 1.000000\nTRANSPARENCY 0.000000 0.000000 0.000000 1.000000\nAMBIENTCOLOR 1.000000 1.000000 1.000000 1.000000\nINCANDESCENCE 0.000000 0.000000 0.000000 1.000000\nCOEFFS 0.800000 0.000000\nGLOW 0.000000 0\nREFRACTIVE 6 1.000000\nSPECULARCOLOR 0.500000 0.500000 0.500000 1.000000\nREFLECTIVECOLOR 0.000000 0.000000 0.000000 1.000000\nREFLECTIVE 1 0.500000\nBLINN -1.000000 -1.000000\nPHONG 20.000000\n";
        MaterialIndex++;
    }
    // text mode, as before: each "\n" written "\r\n"
    std::ofstream Writer(FileName);
    if (!Writer) throw std::runtime_error("cannot create " + FileName);
    Writer.write(Out.data(), (std::streamsize)Out.size());
    if (!Writer) throw std::runtime_error("cannot write " + FileName);
}
