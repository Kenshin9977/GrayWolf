#include "stdafx.h"

#include "OBJExport.h"

#include "Strings.h"
#include "FileSystems.h"
#include "WraithModel.h"

#include <filesystem>
#include <format>
#include <fstream>
#include <stdexcept>

void WavefrontOBJ::ExportOBJ(const WraithModel& Model, const std::string& FileName)
{
    std::ofstream Writer(FileName);
    if (!Writer) throw std::runtime_error("cannot create " + FileName);
    Writer.rdbuf()->pubsetbuf(nullptr, 0x100000);   // MSVC: a 1 MB buffer, the file comes in small pieces
    Writer << "# Generated by Wraith - Game extraction tools\n"
        "# Please credit DTZxPorter for using it!\n" << '\n';
    // every face's three corners in turn, a line each: positions, then UVs, then normals
    const auto EachCorner = [&](const auto& Line) {
        for (auto& Submesh : Model.Submeshes)
            for (auto& Face : Submesh.Faces)
                for (const uint32_t Index : { Face.Index1, Face.Index2, Face.Index3 })
                    Writer << Line(Submesh.Verticies[Index]);
    };
    EachCorner([](const WraithVertex& V) { return std::format("v {:f} {:f} {:f}\n", V.Position.X, V.Position.Y, V.Position.Z); });
    EachCorner([](const WraithVertex& V) { return std::format("vt {:f} {:f}\n", V.UVLayers[0].U, (1 - V.UVLayers[0].V)); });
    EachCorner([](const WraithVertex& V) { return std::format("vn {:f} {:f} {:f}\n", V.Normal.X, V.Normal.Y, V.Normal.Z); });
    std::unordered_set<int32_t> UniqueMaterials;
    uint32_t VertexIndex = 1;
    for (auto& Submesh : Model.Submeshes)
    {
        const WraithMaterial& Material = (Submesh.MaterialIndicies[0] > -1) ? Model.Materials[Submesh.MaterialIndicies[0]] : WraithMaterial::DefaultMaterial;
        Writer << std::format(
            "mtllib {}.mtl\n"
            "g {}\n"
            "usemtl {}",
            Material.MaterialName.c_str(),
            Material.MaterialName.c_str(),
            Material.MaterialName.c_str()
            ) << '\n';
        UniqueMaterials.insert(Submesh.MaterialIndicies[0]);
        for (auto& Face : Submesh.Faces)
        {
            Writer << std::format(
                "f {}/{}/{} {}/{}/{} {}/{}/{}",
                (VertexIndex + 2), (VertexIndex + 2), (VertexIndex + 2),
                (VertexIndex + 1), (VertexIndex + 1), (VertexIndex + 1),
                VertexIndex, VertexIndex, VertexIndex
                ) << '\n';
            VertexIndex += 3;
        }
    }
    auto MaterialPath = FileSystems::GetDirectoryName(FileName);
    for (auto& MaterialIndex : UniqueMaterials)
    {
        const WraithMaterial& Material = (MaterialIndex > -1) ? Model.Materials[MaterialIndex] : WraithMaterial::DefaultMaterial;
        const auto MtlPath = (std::filesystem::path(MaterialPath) / (Material.MaterialName + ".mtl")).string();
        std::ofstream MatWriter(MtlPath);
        if (!MatWriter) throw std::runtime_error("cannot create " + MtlPath);
        MatWriter << std::format("newmtl {}\n", Material.MaterialName.c_str());
        MatWriter << "illum 4\nKd 0.00 0.00 0.00\nKa 0.00 0.00 0.00\nKs 0.50 0.50 0.50\n";
        if (!Strings::IsNullOrWhiteSpace(Material.DiffuseMapName))
        {
            MatWriter << std::format("map_Kd {}\n", Material.DiffuseMapName.c_str());
        }
        if (!Strings::IsNullOrWhiteSpace(Material.NormalMapName))
        {
            MatWriter << std::format("map_bump {}\n", Material.NormalMapName.c_str());
        }
        if (!Strings::IsNullOrWhiteSpace(Material.SpecularMapName))
        {
            MatWriter << std::format("map_Ks {}\n", Material.SpecularMapName.c_str());
        }
    }
}