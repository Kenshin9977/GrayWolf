    std::pair<std::string, std::string> WeaponDocument(const std::string& Name, bool Unique, const std::string& Gun,
                                                       const std::string& Hands, const std::vector<std::string>& Anims)
    {
        std::string Text = "gun\t" + Gun + "\nhands\t" + Hands + "\n";
        for (const auto& A : Anims)
            if (!A.empty()) Text += "anim\t" + A + "\n";
        return { std::string(Unique ? "attachmentunique/" : "weapons/") + Name + ".weapon", std::move(Text) };
    }

    Facts Parse(const std::vector<std::pair<std::string, std::string>>& Docs, const Rules& R)
    {
        static const std::regex AnimTree(R"re(self\.animTree\s*=\s*"([^"]*)")re", std::regex::icase);
        static const std::regex CharacterCall(R"re(character[\\/](\w+)::main\s*\(\s*\))re", std::regex::icase);
        static const std::regex SetModel(R"re(setModel\s*\(\s*"([^"]+)")re", std::regex::icase);
        static const std::regex SetModelAlias(R"re(setModelFromArray\s*\(\s*xmodelalias[\\/](\w+)::main)re", std::regex::icase);
        static const std::regex HeadModel(R"re(headModel\s*=\s*"([^"]+)")re", std::regex::icase);
        static const std::regex HeadAlias(R"re(headModel\s*=\s*codescripts[\\/]character::randomElement\s*\(\s*xmodelalias[\\/](\w+)::main)re", std::regex::icase);
        static const std::regex AliasEntry(R"re(\[\s*\d+\s*\]\s*=\s*"([^"]+)")re");
        Facts F;
        for (const auto& [Name, Text] : Docs)
        {
            const auto [Folder, Stem] = FolderStem(Name);
            const std::string Ext = fs::path(Lower(Name)).extension().string();
            if (Ext == ".atr")
            {
                TreeAnims(Stem, Text, F);
                continue;
            }
            if (Ext == ".weapon")
            {
                ParseWeapon(Folder, Stem, Text, F);
                continue;
            }
            if (Ext != ".gsc" && Ext != ".csc") continue;
            if (Compiled C; ReadCompiled(Text, C))
            {
                ParseCompiled(Folder, Stem, C, R, F);
                continue;
            }
            if (Folder == "aitype" || (Folder == "mptype" && R.PlayerTypes))
            {
                const std::string Main = MainOf(Text);
                Type Ty;
                Ty.Kind = Folder;
                Ty.Name = Stem;
                // an AI's tree as its type names it ("" the default, "dog.atr"); a player's the engine's
                Ty.Tree = Folder == "mptype" ? R.PlayerTree : FolderStem(First(Main, AnimTree)).second;
                if (Ty.Tree.empty()) Ty.Tree = R.AiTree;
                for (std::sregex_iterator It(Main.begin(), Main.end(), CharacterCall), End; It != End; ++It)
                    Ty.Characters.push_back(Lower((*It)[1].str()));
                if (!Ty.Characters.empty()) F.Types.push_back(std::move(Ty));
            }
            else if (Folder == "character")
            {
                const std::string Main = MainOf(Text);
                Character& Ch = F.Characters[Stem];
                Ch.Body = First(Main, SetModel);
                Ch.BodyAlias = Lower(First(Main, SetModelAlias));
                Ch.Head = First(Main, HeadModel);
                Ch.HeadAlias = Lower(First(Main, HeadAlias));
            }
            else if (Folder == "xmodelalias")
            {
                auto& List = F.Aliases[Stem];
                for (std::sregex_iterator It(Text.begin(), Text.end(), AliasEntry), End; It != End; ++It) List.push_back((*It)[1].str());
            }
            else
                ParsePlayers(Folder, Stem, Text, F);
            ScriptAnims(Text, F);
        }
        if (!F.CacBodies.empty()) F.Players.push_back({ "*cac", R.PlayerTree, {}, {}, {} });   // resolved by Own, across sources
        return F;
    }

    void Own(const std::vector<const Facts*>& All, const std::vector<std::string>& Anims, AnimOwners::Book& Out, const Options& O)
    {
        const Sources S{ All };
        // each tree's owners: the types of it of the first source holding any
        std::map<std::string, std::vector<std::string>> OwnersOf;
        std::map<std::string, std::vector<const Type*>> TypesOf;
        const auto Owners = [&](const std::string& Tree) -> const std::vector<std::string>& {
            const auto [It, New] = OwnersOf.try_emplace(Tree);
            if (!New) return It->second;
            for (const Facts* F : All)
            {
                for (const Type& Ty : F->Types)
                {
                    AnimOwners::Owner Ow;
                    if (Ty.Tree != Tree || !S.OwnerOf(Ty, Ow)) continue;
                    const std::string Id = Ty.Kind + ":" + Ty.Name;
                    Out.Owners[Id] = std::move(Ow);
                    It->second.push_back(Id);
                    TypesOf[Tree].push_back(&Ty);
                }
                if (!It->second.empty()) break;
            }
            return It->second;
        };
        // each tree's players: those of it of the first source holding any
        std::map<std::string, std::vector<std::string>> PlayersOf;
        const auto Players = [&](const std::string& Tree) -> const std::vector<std::string>& {
            const auto [It, New] = PlayersOf.try_emplace(Tree);
            if (!New) return It->second;
            for (const Facts* F : All)
            {
                for (const Player& P : F->Players)
                {
                    if (!PlayerFits(P.Tree, Tree)) continue;
                    std::vector<Player> List;
                    if (P.Id == "*cac") List = S.CacPlayers(P.Tree);
                    else List.push_back(P);
                    for (const Player& Q : List)
                    {
                        AnimOwners::Owner Ow;
                        Ow.Models = Q.Models;
                        Ow.Source = Q.Source;
                        if (!Q.Character.empty() && !S.ModelsOf(Q.Character, Ow.Models)) continue;
                        if (Ow.Models.empty() || std::find(It->second.begin(), It->second.end(), Q.Id) != It->second.end()) continue;
                        Out.Owners[Q.Id] = std::move(Ow);
                        It->second.push_back(Q.Id);
                    }
                }
                if (!It->second.empty()) break;
            }
            return It->second;
        };

        // the weapons naming each anim, and a weapon stem's variant (an attachment unique's base)
        std::map<std::string, std::vector<std::pair<std::string, const Weapon*>>> WeaponsOf;
        std::map<std::string, std::pair<std::string, const Weapon*>> ByStem;
        for (const Facts* F : All)
            for (const auto& [Name, W] : F->Weapons)
            {
                for (const auto& A : W.Anims) WeaponsOf[A].emplace_back(Name, &W);
                if (!W.Unique && !W.Gun.empty()) ByStem.try_emplace(WeaponStem(Name), Name, &W);
            }
        // a weapon naming no hands is held by the players' arms (the first source's first)
        std::string ViewHands;
        for (const Facts* F : All)
            if (!F->ViewHands.empty()) { ViewHands = F->ViewHands.front(); break; }
        // an attachment unique's base weapon: the longest weapon stem it starts with ("au_" left out)
        const auto BaseOf = [&](std::string Name) -> const std::pair<std::string, const Weapon*>* {
            if (Name.rfind("au_", 0) == 0) Name = Name.substr(3);
            for (std::string P = WeaponStem(Name);;)
            {
                if (const auto It = ByStem.find(P); It != ByStem.end()) return &It->second;
                const size_t U = P.rfind('_');
                if (U == std::string::npos) return nullptr;
                P.resize(U);
            }
        };

        // AI types' bodies whose tree lists no anim anywhere (the anims are named after the model)
        std::vector<std::pair<std::string, std::string>> ByPrefix;   // (body_, type id)
        if (O.ByModelPrefix)
            for (const Facts* F : All)
                for (const Type& Ty : F->Types)
                {
                    bool Listed = false;
                    for (const Facts* G : All) Listed |= G->Trees.count(Ty.Tree) && !G->Trees.at(Ty.Tree).empty();
                    AnimOwners::Owner Ow;
                    if (Listed || !S.OwnerOf(Ty, Ow)) continue;
                    const std::string Id = Ty.Kind + ":" + Ty.Name;
                    ByPrefix.emplace_back(Lower(Ow.Models.front()) + "_", Id);
                    Out.Owners.try_emplace(Id, std::move(Ow));
                }

        for (const auto& Anim : Anims)
        {
            const std::string L = Lower(Anim);
            const std::set<std::string> AnimWords = Words(L);
            std::set<std::string> Trees;
            for (const Facts* F : All)
                for (const auto& [Tree, In] : F->Trees)
                    if (In.count(L)) Trees.insert(Tree);
            bool Owned = false;
            for (const auto& Tree : Trees)
            {
                std::vector<std::string> Ids = Owners(Tree);
                if (O.ByNameTokens && Ids.size() > 1)
                {
                    // the words of the types' names not all of them share, the anim's first
                    const auto& Types = TypesOf[Tree];
                    std::map<std::string, size_t> Count;
                    for (const Type* Ty : Types)
                        for (const auto& W : Words(Ty->Name)) Count[W]++;
                    std::map<std::string, size_t> Score;
                    for (const Type* Ty : Types)
                        for (const auto& W : Words(Ty->Name))
                            if (Count[W] < Types.size() && AnimWords.count(W)) Score[Ty->Kind + ":" + Ty->Name]++;
                    std::stable_sort(Ids.begin(), Ids.end(), [&](const std::string& A, const std::string& B) { return Score[A] > Score[B]; });
                }
                for (const auto& Id : Ids) Out.Own(Anim, Id);
                for (const auto& Id : Players(Tree)) Out.Own(Anim, Id);
                Owned |= !Ids.empty() || !Players(Tree).empty();
            }
            if (const auto W = WeaponsOf.find(L); W != WeaponsOf.end())
            {
                // (weapon id, its gun and hands), nearest name first, one per gun model
                struct Pick { std::string Id; const Weapon* W; size_t Score; };
                std::vector<Pick> Picks;
                for (const auto& [Name, Wp] : W->second)
                {
                    const std::pair<std::string, const Weapon*>* Base = nullptr;
                    std::pair<std::string, const Weapon*> Self{ Name, Wp };
                    if (Wp->Unique) Base = BaseOf(Name);
                    else if (!Wp->Gun.empty()) Base = &Self;
                    if (!Base) continue;
                    size_t Score = 0;
                    // its name's words in the anim's ("perk" in viewmodel_zombie_perksacola_idle)
                    for (const auto& Wd : Words(WeaponStem(Name)))
                        Score += std::any_of(AnimWords.begin(), AnimWords.end(), [&](const std::string& A) {
                            return A == Wd || (Wd.size() >= 3 && A.find(Wd) != std::string::npos);
                        });
                    Picks.push_back({ Base->first, Base->second, Score });
                }
                std::stable_sort(Picks.begin(), Picks.end(), [](const Pick& A, const Pick& B) {
                    return A.Score != B.Score ? A.Score > B.Score : A.Id.size() != B.Id.size() ? A.Id.size() < B.Id.size() : A.Id < B.Id;
                });
                std::set<std::string> Guns;
                for (const auto& P : Picks)
                {
                    if (Guns.size() >= O.WeaponOwners || !Guns.insert(Lower(P.W->Gun)).second) continue;
                    const std::string Id = "weapon:" + P.Id;
                    AnimOwners::Owner& Ow = Out.Owners[Id];
                    Ow.Models = { P.W->Gun };
                    if (!P.W->Hands.empty()) Ow.Models.push_back(P.W->Hands);
                    else if (!ViewHands.empty()) Ow.Models.push_back(ViewHands);
                    Ow.Source = "weapon " + P.Id + (P.W->Hands.empty() && !ViewHands.empty() ? " (the players' arms)" : "");
                    Out.Own(Anim, Id);
                    Owned = true;
                }
            }
            if (!Owned)
                for (const auto& [Prefix, Id] : ByPrefix)
                    if (L.rfind(Prefix, 0) == 0) Out.Own(Anim, Id);
        }
    }
